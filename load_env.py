"""PlatformIO pre-build script: turns .env into a generated wifi_secrets.h.

The header is written to the build directory, so credentials never live in
source files. Real environment variables take priority over .env.
Copy .env.example to .env to get started.
"""
import os

Import("env")

KEYS = ("WIFI_AP_SSID", "WIFI_AP_PASSWORD", "WIFI_STA_SSID", "WIFI_STA_PASSWORD")


def read_dotenv(path):
    values = {}
    if not os.path.isfile(path):
        return values
    with open(path, encoding="utf-8-sig") as dotenv:
        for line in dotenv:
            line = line.strip()
            if not line or line.startswith("#") or "=" not in line:
                continue
            key, value = line.split("=", 1)
            value = value.strip()
            if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
                value = value[1:-1]
            values[key.strip()] = value
    return values


def c_string(value):
    return '"%s"' % value.replace("\\", "\\\\").replace('"', '\\"')


dotenv_values = read_dotenv(os.path.join(env.subst("$PROJECT_DIR"), ".env"))
lines = ["#pragma once", "// Generated by load_env.py. Do not edit or commit."]
for key in KEYS:
    value = os.environ.get(key, dotenv_values.get(key))
    if value:
        lines.append("#define %s %s" % (key, c_string(value)))
    else:
        lines.append('#error "%s is not set. Copy .env.example to .env and fill it in."' % key)
content = "\n".join(lines) + "\n"

generated_dir = os.path.join(env.subst("$BUILD_DIR"), "generated")
os.makedirs(generated_dir, exist_ok=True)
header = os.path.join(generated_dir, "wifi_secrets.h")

existing = None
if os.path.isfile(header):
    with open(header, encoding="utf-8") as current:
        existing = current.read()
if existing != content:  # Rewriting an unchanged header would force a rebuild.
    with open(header, "w", encoding="utf-8") as output:
        output.write(content)

env.Append(CPPPATH=[generated_dir])
